function parseNotams(text) {
  return splitBlocks(text)
    .map(parseBlock)
    .filter(Boolean);
}

function splitBlocks(text) {
  const normalized = text.replace(/\r/g, '').trim();
  if (!normalized) return [];
  const matches = normalized.match(/\([A-Z]\d{4}\/\d{2}[\s\S]*?\)(?=\s*\([A-Z]\d{4}\/\d{2}|\s*$)/g);
  return matches || normalized.split(/\n\s*\n/).filter(Boolean);
}

function parseBlock(block) {
  const compact = block.replace(/\s+/g, ' ').trim();
  const id = compact.match(/[A-Z]\d{4}\/\d{2}/)?.[0];
  if (!id) return null;

  const icao = readField(compact, 'A') || 'RCAA';
  const start = parseNotamTime(readField(compact, 'B'));
  const end = parseNotamTime(readField(compact, 'C'));
  const lower = readField(compact, 'F') || 'GND';
  const upper = stripClosing(readField(compact, 'G') || '');
  const eText = readField(compact, 'E') || compact;
  const qText = readField(compact, 'Q') || '';
  const qShape = parseQCoordinate(qText);
  const points = extractCoordinates(eText);
  const radius = extractRadius(eText) || qShape?.radius || 1000;

  let type = 'text';
  let center = null;
  let polygon = [];
  if (points.length >= 3 && !extractRadius(eText)) {
    type = 'polygon';
    polygon = points;
  } else if (points.length >= 1 || qShape) {
    type = 'circle';
    center = points[0] || qShape.center;
  }

  return {
    id,
    icao,
    title: makeTitle(eText),
    status: statusFromTime(start, end),
    type,
    ...(center ? { center } : {}),
    ...(type === 'circle' ? { radius } : {}),
    ...(polygon.length ? { points: polygon } : {}),
    lower,
    upper,
    start: start || '',
    end: end || '',
    summary: eText,
    raw: block.trim(),
  };
}

function readField(text, field) {
  const next = field === 'Q' ? 'A' : String.fromCharCode(field.charCodeAt(0) + 1);
  const pattern = new RegExp(`${field}\\)\\s*([\\s\\S]*?)(?=\\s${next}\\)|\\s[A-G]\\)|$)`);
  return text.match(pattern)?.[1]?.trim() || '';
}

function stripClosing(value) {
  return value.replace(/\)+$/g, '').trim();
}

function parseQCoordinate(qText) {
  const match = qText.match(/(\d{2})(\d{2})([NS])(\d{3})(\d{2})([EW])(\d{3})?$/);
  if (!match) return null;
  const lat = dmsToDecimal(match[1], match[2], '0', match[3]);
  const lng = dmsToDecimal(match[4], match[5], '0', match[6]);
  const radius = match[7] ? Number(match[7]) * 1852 : 1000;
  return { center: [roundCoord(lat), roundCoord(lng)], radius };
}

function extractCoordinates(text) {
  const coords = [];
  const re = /(\d{2})(\d{2})(\d{2})?([NS])\s*(\d{3})(\d{2})(\d{2})?([EW])/g;
  let match;
  while ((match = re.exec(text))) {
    const lat = dmsToDecimal(match[1], match[2], match[3] || '0', match[4]);
    const lng = dmsToDecimal(match[5], match[6], match[7] || '0', match[8]);
    coords.push([roundCoord(lat), roundCoord(lng)]);
  }
  return coords;
}

function dmsToDecimal(deg, min, sec, hemi) {
  const value = Number(deg) + Number(min) / 60 + Number(sec || 0) / 3600;
  return /[SW]/.test(hemi) ? -value : value;
}

function roundCoord(value) {
  return Math.round(value * 1e6) / 1e6;
}

function extractRadius(text) {
  const match = text.match(/(?:WI|WITHIN|RADIUS OF|RDO)?\s*(\d+(?:\.\d+)?)\s*(NM|KM|M)\s*(?:RADIUS|RDO)?/i);
  if (!match) return null;
  const value = Number(match[1]);
  const unit = match[2].toUpperCase();
  if (unit === 'NM') return Math.round(value * 1852);
  if (unit === 'KM') return Math.round(value * 1000);
  return Math.round(value);
}

function parseNotamTime(value) {
  const clean = String(value || '').match(/\d{10}/)?.[0];
  if (!clean) return '';
  const year = 2000 + Number(clean.slice(0, 2));
  const month = clean.slice(2, 4);
  const day = clean.slice(4, 6);
  const hour = clean.slice(6, 8);
  const minute = clean.slice(8, 10);
  return `${year}-${month}-${day} ${hour}:${minute} UTC`;
}

function statusFromTime(startText, endText) {
  const now = Date.now();
  const start = Date.parse(startText.replace(' UTC', 'Z').replace(' ', 'T'));
  const end = Date.parse(endText.replace(' UTC', 'Z').replace(' ', 'T'));
  if (Number.isFinite(end) && now > end) return 'expired';
  if (Number.isFinite(start) && now < start) return 'planned';
  return 'active';
}

function makeTitle(text) {
  const cleaned = text.replace(/\s+/g, ' ').trim();
  if (!cleaned) return 'NOTAM';
  return cleaned.length > 34 ? `${cleaned.slice(0, 34)}...` : cleaned;
}

function formatLocalTime(date) {
  const local = new Date(date.getTime() + 8 * 60 * 60 * 1000);
  const pad = (value) => String(value).padStart(2, '0');
  return `${local.getUTCFullYear()}-${pad(local.getUTCMonth() + 1)}-${pad(local.getUTCDate())} ${pad(local.getUTCHours())}:${pad(local.getUTCMinutes())}`;
}
